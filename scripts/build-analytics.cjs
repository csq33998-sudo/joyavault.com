// Only the public GA4 measurement ID is exposed; no other environment values.
const fs = require('node:fs');
const path = require('node:path');
function config(env) {
  const measurementId = (env.GA4_MEASUREMENT_ID || '').trim();
  if (measurementId && !/^G-[A-Z0-9]+$/.test(measurementId)) {
    throw new Error('GA4_MEASUREMENT_ID must be a GA4 measurement ID starting with G-.');
  }
  return `/* Generated by scripts/build-analytics.cjs. */\nwindow.JoyaAnalyticsConfig = ${JSON.stringify({measurementId})};\n`;
}
if (require.main === module) {
  const saved = JSON.parse(fs.readFileSync(path.join(__dirname, '../src/data/analytics.json'), 'utf8'));
  // The measurement ID is public. An environment value overrides the saved site
  // setting; explicitly setting it to an empty string disables initialization.
  const measurementId = process.env.GA4_MEASUREMENT_ID ?? saved.measurementId;
  fs.writeFileSync(path.join(__dirname, '../js/analytics-config.js'), config({GA4_MEASUREMENT_ID: measurementId}));
  console.log('GA4 configuration generated (disabled when measurement ID is empty).');
}
module.exports = { config };
