// Build static Pages output without publishing source data or developer files.
const fs = require('node:fs');
const path = require('node:path');
require('./check-translations.cjs').check();
const { config: analyticsConfig } = require('./build-analytics.cjs');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'dist');
const marker = path.join(out, '.joyavault-pages-build');
const languages = ['en', 'zh', 'de', 'fr', 'it', 'pl', 'pt', 'ar'];
const routing = JSON.parse(fs.readFileSync(path.join(root, 'vercel.json'), 'utf8'));
const redirects = new Map();
const translated = JSON.parse(fs.readFileSync(path.join(root, 'src/translations/published.json'), 'utf8'));
for (const rule of routing.redirects) {
  // Pages normalizes directory/index URLs itself. Do not spend thousands of
  // explicit redirect rules on synthetic aliases for newly translated routes.
  if (translated[rule.destination] && [rule.destination.slice(0, -1), `${rule.destination}index.html`, `${rule.destination}index`, `${rule.destination.slice(0, -1)}.html`].includes(rule.source)) continue;
  if (!/^\/[\w/.-]*$/.test(rule.source) || !/^\/[\w/.-]*$/.test(rule.destination)) {
    throw new Error(`Unsupported redirect syntax: ${rule.source}`);
  }
  if (![301, 302, 303, 307, 308].includes(rule.statusCode)) throw new Error('Unsupported redirect status');
  if (redirects.has(rule.source)) throw new Error(`Duplicate redirect: ${rule.source}`);
  redirects.set(rule.source, rule);
}
if (redirects.size > 2000) throw new Error('Pages static redirect limit exceeded');
for (const rule of redirects.values()) {
  const seen = new Set([rule.source]);
  let target = rule.destination;
  while (redirects.has(target)) {
    if (seen.has(target)) throw new Error(`Redirect loop: ${rule.source}`);
    seen.add(target);
    target = redirects.get(target).destination;
  }
  const file = path.join(root, target, target.endsWith('/') ? 'index.html' : '');
  if (!fs.existsSync(file)) throw new Error(`Missing redirect target: ${target}`);
}
// Pages serves directory index files natively. Reject any new, nontrivial rewrite.
for (const rule of routing.rewrites || []) {
  if (!rule.source.endsWith('/') || rule.destination !== `${rule.source}index.html`) {
    throw new Error(`Rewrite needs manual migration: ${rule.source}`);
  }
}
if (fs.existsSync(out)) {
  if (fs.lstatSync(out).isSymbolicLink() || fs.realpathSync(out) !== out || !fs.existsSync(marker)) {
    throw new Error('dist is not a recognized generated output directory; preserve it and move it before building.');
  }
  if (path.dirname(out) !== root || path.basename(out) !== 'dist') throw new Error('Unsafe output path');
  fs.rmSync(out, { recursive: true });
}
fs.mkdirSync(out);
fs.writeFileSync(marker, 'Generated by scripts/build-cloudflare.cjs\n');
const allowed = new Set(['.html', '.css', '.js', '.json', '.jpg', '.jpeg', '.png', '.webp', '.gif', '.svg', '.ico', '.avif', '.woff', '.woff2', '.ttf', '.mp4', '.webm']);
function copyDirectory(from, to) {
  if (!fs.existsSync(from)) return;
  for (const item of fs.readdirSync(from, { withFileTypes: true })) {
    if (item.name.startsWith('.') || item.isSymbolicLink()) continue;
    const source = path.join(from, item.name);
    const dest = path.join(to, item.name);
    if (item.isDirectory()) copyDirectory(source, dest);
    else if (allowed.has(path.extname(item.name).toLowerCase())) {
      fs.mkdirSync(to, { recursive: true });
      fs.copyFileSync(source, dest);
    }
  }
}
for (const dir of [...languages, 'assets', 'css', 'js', 'articles', 'blog']) {
  copyDirectory(path.join(root, dir), path.join(out, dir));
}
const rootFiles = fs.readdirSync(root).filter(name => name.endsWith('.css') || ['robots.txt', 'sitemap.xml'].includes(name));
for (const name of rootFiles) fs.copyFileSync(path.join(root, name), path.join(out, name));
const saved = JSON.parse(fs.readFileSync(path.join(root, 'src/data/analytics.json'), 'utf8'));
fs.writeFileSync(path.join(out, 'js/analytics-config.js'), analyticsConfig({ GA4_MEASUREMENT_ID: process.env.GA4_MEASUREMENT_ID ?? saved.measurementId }));
fs.writeFileSync(path.join(out, 'index.html'), '<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>JoyaVault</title><link rel="canonical" href="https://joyavault.com/en/"><meta http-equiv="refresh" content="0;url=/en/"></head><body><p><a href="/en/">Continue to JoyaVault</a></p></body></html>\n');
fs.writeFileSync(path.join(out, '404.html'), '<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Page not found | JoyaVault</title><meta name="robots" content="noindex"></head><body><main><h1>Page not found</h1><p>This page may have moved or no longer exists.</p><a href="/en/">Explore JoyaVault</a></main></body></html>\n');
fs.writeFileSync(path.join(out, '_redirects'), [...redirects.values()].map(r => `${r.source} ${r.destination} ${r.statusCode}`).join('\n') + '\n');
const headers = [
  'https://:project.pages.dev/*\n  X-Robots-Tag: noindex',
  'https://:version.:project.pages.dev/*\n  X-Robots-Tag: noindex',
];
const revalidate = ['/', '/index.html', '/404.html', '/robots.txt', '/sitemap.xml', ...languages.map(l => `/${l}/*`), '/articles/*', '/blog/*', '/js/*'];
for (const pattern of revalidate) headers.push(`${pattern}\n  Cache-Control: public, max-age=0, must-revalidate`);
for (const pattern of ['/css/*', ...rootFiles.filter(f => f.endsWith('.css')).map(f => `/${f}`)]) {
  headers.push(`${pattern}\n  Cache-Control: public, max-age=3600`);
}
headers.push('/assets/*\n  Cache-Control: public, max-age=86400');
fs.writeFileSync(path.join(out, '_headers'), headers.join('\n\n') + '\n');
function filesIn(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => e.isDirectory() ? filesIn(path.join(dir, e.name)) : [path.join(dir, e.name)]);
}
const files = filesIn(out);
if (files.length > 20000) throw new Error('Pages Free file count limit exceeded');
for (const file of files) if (fs.statSync(file).size > 25 * 1024 * 1024) throw new Error(`Asset exceeds 25 MiB: ${file}`);
console.log(`Ready: ${files.length} files, ${redirects.size} redirects, ${headers.length} header rules in dist.`);
console.log(files.length <= 1000 ? 'Within dashboard upload limits.' : 'Use Wrangler or Git integration: dashboard upload limit exceeded.');
